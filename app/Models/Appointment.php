<?php

declare(strict_types=1);

namespace App\Models;

use App\Enums\AppointmentStatus;
use Carbon\CarbonImmutable;
use Database\Factories\AppointmentFactory;
use Illuminate\Database\Eloquent\Attributes\Fillable;
use Illuminate\Database\Eloquent\Attributes\RouteKey;
use Illuminate\Database\Eloquent\Attributes\Scope;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\Concerns\HasUlids;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Database\Eloquent\Relations\HasOne;
use Illuminate\Support\Carbon;

/**
 * @property int $id
 * @property string $ulid
 * @property int $patient_id
 * @property int $doctor_id
 * @property int $service_id
 * @property CarbonImmutable $starts_at UTC
 * @property CarbonImmutable $ends_at UTC
 * @property CarbonImmutable $blocked_until UTC, ends_at plus the service buffer
 * @property AppointmentStatus $status
 * @property int|null $active_key Generated by MySQL: 1 for active statuses, NULL otherwise. Read-only.
 * @property bool $emergency_flag
 * @property CarbonImmutable|null $cancelled_at
 * @property int|null $cancelled_by
 * @property string|null $cancel_reason
 * @property CarbonImmutable|null $checked_in_at
 * @property CarbonImmutable|null $reminder_sent_at
 * @property Carbon|null $created_at
 * @property Carbon|null $updated_at
 */
// `active_key` is not fillable: it is a generated column and MySQL refuses writes to it.
// `status`, `emergency_flag` and the cancel/check-in columns are fillable because Actions call create()/update()
// with them. A Form Request must never accept them from user input.
#[Fillable([
    'patient_id', 'doctor_id', 'service_id',
    'starts_at', 'ends_at', 'blocked_until',
    'status', 'emergency_flag',
    'cancelled_at', 'cancelled_by', 'cancel_reason',
    'checked_in_at', 'reminder_sent_at',
])]
// Private records are addressed by ULID, so IDs in URLs can't be counted up (/appointments/1, /2, ...).
// A Policy is still the real protection.
#[RouteKey('ulid')]
class Appointment extends Model
{
    /** @use HasFactory<AppointmentFactory> */
    use HasFactory, HasUlids;

    /**
     * HasUlids fills the primary key by default. Our primary key is the normal auto-increment `id`,
     * so point it at the `ulid` column instead.
     *
     * @return list<string>
     */
    public function uniqueIds(): array
    {
        return ['ulid'];
    }

    protected function casts(): array
    {
        return [
            'starts_at' => 'immutable_datetime',
            'ends_at' => 'immutable_datetime',
            'blocked_until' => 'immutable_datetime',
            'status' => AppointmentStatus::class,
            'active_key' => 'integer',
            'emergency_flag' => 'boolean',
            'cancelled_at' => 'immutable_datetime',
            'checked_in_at' => 'immutable_datetime',
            'reminder_sent_at' => 'immutable_datetime',
        ];
    }

    /**
     * Appointments that hold a slot (booked, checked in, completed).
     *
     * @param  Builder<Appointment>  $query
     */
    #[Scope]
    protected function active(Builder $query): void
    {
        $query->whereIn('status', AppointmentStatus::active());
    }

    /** @return BelongsTo<User, $this> */
    public function patient(): BelongsTo
    {
        return $this->belongsTo(User::class, 'patient_id');
    }

    /** @return BelongsTo<Doctor, $this> */
    public function doctor(): BelongsTo
    {
        return $this->belongsTo(Doctor::class);
    }

    /** @return BelongsTo<Service, $this> */
    public function service(): BelongsTo
    {
        return $this->belongsTo(Service::class);
    }

    /**
     * Who cancelled it: the patient or a staff member.
     *
     * @return BelongsTo<User, $this>
     */
    public function cancelledBy(): BelongsTo
    {
        return $this->belongsTo(User::class, 'cancelled_by');
    }

    /** @return HasOne<Intake, $this> */
    public function intake(): HasOne
    {
        return $this->hasOne(Intake::class);
    }

    /** @return HasMany<VisitNote, $this> */
    public function visitNotes(): HasMany
    {
        return $this->hasMany(VisitNote::class);
    }
}
